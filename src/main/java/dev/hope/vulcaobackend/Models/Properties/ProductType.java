    private final ProductCategory category;
    /** True if this product requires refrigeration or is naturally perishable. */
    private final boolean perishable;
    /** True if this product must be kept frozen. */
    private final boolean frozen;

    ProductType(String displayName, String description, ProductCategory category,
                boolean perishable, boolean frozen) {
        this.displayName = displayName;
        this.description = description;
        this.category = category;
        this.perishable = perishable;
        this.frozen = frozen;
    }

    public String getDisplayName()      { return displayName;  }
    public String getDescription()      { return description;  }
    public ProductCategory getCategory(){ return category;     }
    public boolean isPerishable()       { return perishable;   }
    public boolean isFrozen()           { return frozen;       }

    /** Shelf-stable = not perishable and not frozen. */
    public boolean isShelfStable()      { return !perishable && !frozen; }

